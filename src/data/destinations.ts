export function getDestination(slug: string) {
  if (slug?.toLowerCase() === "jabalpur") {
    return destinations.find((d) => d.slug === "bhedaghat");
  }
  return destinations.find((d) => d.slug === slug);
}

export function getDestinationsByIds(ids: string[]) {
  return ids
    .map((id) => destinations.find((d) => d.id === id))
    .filter((d): d is Destination => Boolean(d));
}

export function getDestinationsByTheme(theme: string) {
  return destinations.filter((d) => d.themes.includes(theme));
}
