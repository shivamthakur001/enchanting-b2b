import type { Plugin, ViteDevServer } from "vite";
import { createHash } from "crypto";
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from "fs";
import { join, extname } from "path";

const SUPPORTED_EXTS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);
const THEME_SWITCHER_EXTS = new Set([".webp", ".png", ".jpg", ".jpeg", ".svg", ".avif"]);
const THEME_SWITCHER_FOLDERS = ["nature", "heritage", "wildlife", "spiritual"];
const DESTINATION_CARD_FOLDERS = ["nature", "heritage", "wildlife", "spiritual"];
const DESTINATION_CARD_EXTENSIONS = [".webp", ".jpg", ".jpeg", ".png", ".avif"];

/** Natural string sort: e.g. pachmari (2) comes before pachmari (10) */
export function naturalSortCompare(a: string, b: string): number {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
}

export function generateManifestForSlug(slug: string, galleryRoot: string): number {
  const folderPath = join(galleryRoot, slug);
  if (!existsSync(folderPath) || !statSync(folderPath).isDirectory()) return 0;

  const files = readdirSync(folderPath)
    .filter((f) => {
      const ext = extname(f).toLowerCase();
      return SUPPORTED_EXTS.has(ext) && !f.startsWith(".");
    })
    .sort(naturalSortCompare);

  const manifest = {
    slug,
    generatedAt: new Date().toISOString(),
    images: files.map((filename) => ({
      filename,
      path: `/destination-gallery/${slug}/${filename}`,
    })),
  };

  const manifestPath = join(folderPath, "manifest.json");
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), "utf8");
  return files.length;
}

export function generateAllGalleryManifests(galleryRoot: string): void {
  if (!existsSync(galleryRoot)) return;
  const destinations = readdirSync(galleryRoot).filter((name) => {
    return statSync(join(galleryRoot, name)).isDirectory();
  });
  for (const slug of destinations) {
    generateManifestForSlug(slug, galleryRoot);
  }
}

function generateDestinationCardImageManifest(root: string): boolean {
    const sourceRoot = join(root, "public", "destination-card-images");
    const outputPath = join(root, "src", "data", "destinationCardImages.generated.ts");
    const manifest = Object.fromEntries(
      DESTINATION_CARD_FOLDERS.map((folder) => {
        const folderPath = join(sourceRoot, folder);
        const entries: Record<string, { path: string; version: string }> = {};
        if (!existsSync(folderPath)) return [folder, entries];

        for (const file of readdirSync(folderPath)) {
          const extension = extname(file).toLowerCase();
          if (!DESTINATION_CARD_EXTENSIONS.includes(extension)) continue;
          const slug = file.slice(0, -extension.length).toLowerCase();
          const current = entries[slug];
          const currentExtension = current ? extname(current.path).toLowerCase() : "";
          if (current && DESTINATION_CARD_EXTENSIONS.indexOf(extension) >= DESTINATION_CARD_EXTENSIONS.indexOf(currentExtension)) {
            continue;
          }

          entries[slug] = {
            path: `/destination-card-images/${folder}/${file}`,
            version: createHash("sha1").update(readFileSync(join(folderPath, file))).digest("hex").slice(0, 12),
          };
        }
        return [folder, entries];
      }),
    );
    const output = `// Generated by scripts/generate-destination-card-image-manifest.js. Do not edit manually.
export type DestinationCardImageEntry = { path: string; version: string };
export type DestinationCardImageManifest = Record<string, Record<string, DestinationCardImageEntry>>;

export const destinationCardImageManifest: DestinationCardImageManifest = ${JSON.stringify(manifest, null, 2)} as const;
`;
  const previous = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (previous === output) return false;
  writeFileSync(outputPath, output, "utf8");
  return true;
}

function generateThemeSwitcherIllustrationManifest(root: string): boolean {
  const sourceRoot = join(root, "public", "theme-switcher-assets");
  const outputPath = join(root, "src", "data", "themeSwitcherIllustrations.generated.ts");
  const illustrations = THEME_SWITCHER_FOLDERS.flatMap((panel) => {
    const folderPath = join(sourceRoot, panel);
    if (!existsSync(folderPath) || !statSync(folderPath).isDirectory()) return [];

    return readdirSync(folderPath)
      .filter((filename) => THEME_SWITCHER_EXTS.has(extname(filename).toLowerCase()) && !filename.startsWith("."))
      .sort(naturalSortCompare)
      .map((filename, index) => {
        const extension = extname(filename);
        const stem = filename.slice(0, -extension.length).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
        const filePath = join(folderPath, filename);
        const hash = createHash("sha1").update(readFileSync(filePath)).digest("hex").slice(0, 12);
        const column = index % 2;
        return {
          id: `${panel}-${stem}`,
          panel,
          src: `/theme-switcher-assets/${panel}/${filename}?v=${hash}`,
          x: column === 0 ? 18 : 82,
          y: 76 + (index % 3) * 7,
          width: 130,
          opacity: 0.42,
          rotation: column === 0 ? -2 : 2,
          visible: true,
          mobile: {
            x: column === 0 ? 14 : 86,
            y: 75 + (index % 2) * 8,
            width: 76,
            opacity: 0.24,
          },
        };
      });
  });
  const output = `// Generated by vite-gallery-plugin.ts. Do not edit manually.
import type { SwitcherIllustration } from "../components/discover/shared/cinematicThemeSwitcherConfig";

export const discoveredThemeSwitcherIllustrations: SwitcherIllustration[] = ${JSON.stringify(illustrations, null, 2)};
`;
  const previous = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (previous === output) return false;
  writeFileSync(outputPath, output, "utf8");
  return true;
}

/**
 * galleryWatcherPlugin
 * Vite plugin for zero-command automatic gallery photo discovery.
 * - Watches public/destination-gallery/<slug>/* for additions, deletions, renames, replacements
 * - Regenerates destination manifest.json automatically
 * - Notifies Vite dev server via custom HMR event: `gallery:manifest-updated`
 * - Also guarantees fresh manifests on `vite build` via `buildStart`
 */
export function galleryWatcherPlugin(): Plugin {
  let galleryRoot = "";
  let projectRoot = "";

  return {
    name: "vite-plugin-gallery-watcher",

    configResolved(config) {
      projectRoot = config.root;
      galleryRoot = join(config.root, "public", "destination-gallery");
    },

    buildStart() {
      // Auto-generate manifests for build / dev startup
      if (galleryRoot && existsSync(galleryRoot)) {
        generateAllGalleryManifests(galleryRoot);
      }
      if (projectRoot) {
        generateThemeSwitcherIllustrationManifest(projectRoot);
      }
    },

    configureServer(server: ViteDevServer) {
      if (!galleryRoot || !existsSync(galleryRoot)) return;

      // Ensure manifests are up to date on server start
      generateAllGalleryManifests(galleryRoot);

      // Watch destination gallery directory
      server.watcher.add(galleryRoot);

      // Watch destination assets directory (Hero, Highlights, Themes, Packages)
      const assetsRoot = join(galleryRoot, "..", "destination-assets");
      if (existsSync(assetsRoot)) {
        server.watcher.add(assetsRoot);
      }

      // Safe cache-control: ensure destination assets are always revalidated on refresh during dev
      server.middlewares.use((req, res, next) => {
        if (req.url && req.url.startsWith("/destination-assets/")) {
          res.setHeader("Cache-Control", "no-cache, must-revalidate");
        }
        next();
      });

      let debounceTimer: ReturnType<typeof setTimeout> | null = null;
      const pendingSlugs = new Set<string>();

      const handleFileChange = (filePath: string) => {
        const normalized = filePath.replace(/\\/g, "/");

        // Auto-refresh when any destination-asset is replaced, added or deleted
        if (normalized.includes("/destination-assets/")) {
          const ext = extname(filePath).toLowerCase();
          if (SUPPORTED_EXTS.has(ext)) {
            console.log(`[destination-assets] Asset updated: ${filePath}`);
            server.ws.send({ type: "full-reload" });
          }
          return;
        }

        const match = normalized.match(/\/destination-gallery\/([^/]+)\/(.+)$/);
        if (!match) return;

        const [, slug, filename] = match;
        // Ignore manifest.json itself to prevent feedback loops
        if (filename.toLowerCase() === "manifest.json") return;

        const ext = extname(filename).toLowerCase();
        if (!SUPPORTED_EXTS.has(ext)) return;

        pendingSlugs.add(slug);

        if (debounceTimer) clearTimeout(debounceTimer);
        debounceTimer = setTimeout(() => {
          for (const s of pendingSlugs) {
            const count = generateManifestForSlug(s, galleryRoot);
            console.log(`[gallery-watcher] Auto-detected changes in "${s}". Manifest updated with ${count} image(s).`);

            // Broadcast HMR custom event to browser
            server.ws.send({
              type: "custom",
              event: "gallery:manifest-updated",
              data: {
                slug: s,
                count,
                timestamp: Date.now(),
              },
            });
          }
          pendingSlugs.clear();
        }, 120);
      };

      server.watcher.on("add", handleFileChange);
      server.watcher.on("unlink", handleFileChange);
      server.watcher.on("change", handleFileChange);

      const destinationCardRoot = join(projectRoot, "public", "destination-card-images");
      server.watcher.add(destinationCardRoot);
      generateDestinationCardImageManifest(projectRoot);

      let destinationCardTimer: ReturnType<typeof setTimeout> | null = null;
      const handleDestinationCardChange = (filePath: string) => {
        const normalized = filePath.replace(/\\/g, "/");
        if (!normalized.includes("/destination-card-images/")) return;
        if (extname(filePath).toLowerCase() !== "" && !SUPPORTED_EXTS.has(extname(filePath).toLowerCase())) return;
        if (destinationCardTimer) clearTimeout(destinationCardTimer);
        destinationCardTimer = setTimeout(() => {
          const updated = generateDestinationCardImageManifest(projectRoot);
          if (updated) {
            console.log("[destination-card-watcher] Destination card image manifest updated.");
          }
        }, 180);
      };

      server.watcher.on("add", handleDestinationCardChange);
      server.watcher.on("unlink", handleDestinationCardChange);
      server.watcher.on("change", handleDestinationCardChange);

      const themeSwitcherRoot = join(projectRoot, "public", "theme-switcher-assets");
      server.watcher.add(themeSwitcherRoot);
      generateThemeSwitcherIllustrationManifest(projectRoot);

      let themeSwitcherTimer: ReturnType<typeof setTimeout> | null = null;
      const handleThemeSwitcherChange = (filePath: string) => {
        const normalized = filePath.replace(/\\/g, "/");
        if (!normalized.includes("/theme-switcher-assets/")) return;
        if (!THEME_SWITCHER_EXTS.has(extname(filePath).toLowerCase())) return;
        if (themeSwitcherTimer) clearTimeout(themeSwitcherTimer);
        themeSwitcherTimer = setTimeout(() => {
          if (generateThemeSwitcherIllustrationManifest(projectRoot)) {
            console.log("[theme-switcher-watcher] Illustration registry updated.");
            server.ws.send({ type: "full-reload" });
          }
        }, 120);
      };

      server.watcher.on("add", handleThemeSwitcherChange);
      server.watcher.on("unlink", handleThemeSwitcherChange);
      server.watcher.on("change", handleThemeSwitcherChange);
    },
  };
}
