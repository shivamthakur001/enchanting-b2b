import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const root = path.resolve(__dirname, "..");
const sourceRoot = path.join(root, "public", "destination-card-images");
const outputPath = path.join(root, "src", "data", "destinationCardImages.generated.ts");
const folders = ["nature", "heritage", "wildlife", "spiritual"];
const extensions = [".webp", ".jpg", ".jpeg", ".png", ".avif"];

function readImages(folder) {
  const folderPath = path.join(sourceRoot, folder);
  if (!fs.existsSync(folderPath)) return {};

  const files = fs.readdirSync(folderPath, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => extensions.includes(path.extname(name).toLowerCase()));

  const manifest = {};
  for (const file of files) {
    const slug = path.basename(file, path.extname(file)).toLowerCase();
    const extension = path.extname(file).toLowerCase();
    const current = manifest[slug];
    const currentPriority = current ? extensions.indexOf(path.extname(current.path)) : Number.MAX_SAFE_INTEGER;
    const nextPriority = extensions.indexOf(extension);
    if (!current || nextPriority < currentPriority) {
      const contents = fs.readFileSync(path.join(folderPath, file));
      manifest[slug] = {
        path: `/destination-card-images/${folder}/${file}`,
        version: crypto.createHash("sha1").update(contents).digest("hex").slice(0, 12),
      };
    }
  }
  return manifest;
}

fs.mkdirSync(sourceRoot, { recursive: true });
for (const folder of folders) fs.mkdirSync(path.join(sourceRoot, folder), { recursive: true });

const manifest = Object.fromEntries(folders.map((folder) => [folder, readImages(folder)]));
const output = `// Generated by scripts/generate-destination-card-image-manifest.js. Do not edit manually.
export type DestinationCardImageEntry = { path: string; version: string };
export type DestinationCardImageManifest = Record<string, Record<string, DestinationCardImageEntry>>;

export const destinationCardImageManifest: DestinationCardImageManifest = ${JSON.stringify(manifest, null, 2)} as const;
`;

const previous = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
if (previous !== output) fs.writeFileSync(outputPath, output);
console.log(`[destination-card-images] Generated ${Object.values(manifest).reduce((count, folder) => count + Object.keys(folder).length, 0)} image entries.`);
